/**
 * Generates an immutable, freshly instantiated DesignDocument from a template model
 * with newly minted unique IDs for document, pages, and objects.
 */
export function instantiateTemplate(template: DesignTemplateDefinition): DesignDocument {
  const baseDoc = template.createDocument();
  const now = new Date().toISOString();
  const newDocId = `doc-${Date.now()}-${Math.random().toString(36).substring(2, 9)}`;

  const newPages: DesignPage[] = baseDoc.pages.map((p, pageIdx) => {
    const newPageId = `page-${pageIdx + 1}-${Date.now()}-${Math.random().toString(36).substring(2, 7)}`;
    return {
      ...p,
      id: newPageId,
      elements: p.elements.map((el) => {
        const newElId = `el-${el.type}-${Date.now()}-${Math.random().toString(36).substring(2, 7)}`;
        return {
          ...JSON.parse(JSON.stringify(el)),
          id: newElId,
        };
      }),
    };
  });

  return {
    ...JSON.parse(JSON.stringify(baseDoc)),
    id: newDocId,
    metadata: {
      ...baseDoc.metadata,
      templateId: template.id,
      createdAt: now,
      updatedAt: now,
    },
    pages: newPages,
  };
}

